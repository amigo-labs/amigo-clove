/**
 * DoveZ level report: a table of all 27 levels from the built assets (`assets/dovez`) —
 * length, music, enemy types and spawns, bosses with parts and hit points, radio messages,
 * weapons. Writes `docs/measurements/dovez-levels.md` (`bun run levels:report`);
 * `--check` only verifies that the file is up to date (CI).
 */
import { join } from "node:path";
import { LEVEL_SLUGS, loadTestLevel } from "../packages/game-dovez/test/assets";

const OUT = join(import.meta.dir, "../docs/measurements/dovez-levels.md");

const rows: string[] = [];
for (const slug of LEVEL_SLUGS) {
  const { level } = await loadTestLevel(slug);
  // Layer 4 timeline (enemies, sounds, radio); kind 0 = enemy, 2 = radio message
  const entries = level.layers[4]?.entries ?? [];
  const spawns = entries.filter((e) => e.kind === 0).length;
  const radio = entries.filter((e) => e.kind === 2).length;
  const bosses = level.enemies
    .filter((e) => e.boss > 0)
    .map((e) => `${e.name} (${e.hitPoints} HP, ${e.parts.length} parts)`);
  const boss = bosses.length > 0 ? bosses.join(", ") : "–";
  const length = level.levelLength >= 99999 ? "Boss" : String(level.levelLength);
  rows.push(
    `| \`${slug}\` | ${level.title} | ${length} | ${level.music || "–"} | ${level.enemies.length} | ${spawns} | ${boss} | ${radio} | ${level.weapons.length} | ${level.routes.length} |`,
  );
}

const text = `# DoveZ — Level report

Generated by \`scripts/dovez-levels.ts\` (\`bun run levels:report\`) from the built assets;
do not edit by hand. The tests \`packages/game-dovez/test/levels.test.ts\` play each of
these levels with a bot to the end (boss defeated or level end reached).

| Level | Title | Length (ticks) | Music | Enemy types | Spawns | Boss | Radio | Weapons | Routes |
|---|---|---|---|---|---|---|---|---|---|
${rows.join("\n")}

Length “Boss”: the level ends with the boss's death (\`levelLength\` 99999).
`;

if (process.argv.includes("--check")) {
  const current = await Bun.file(OUT)
    .text()
    .catch(() => "");
  if (current !== text) {
    console.error("docs/measurements/dovez-levels.md is outdated: `bun run levels:report`");
    process.exit(1);
  }
  console.log("Level report up to date.");
} else {
  await Bun.write(OUT, text);
  console.log(`written: ${OUT}`);
}
